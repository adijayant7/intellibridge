r"""IntelliBridge - train the anomaly model (Mahalanobis on spectral features)
and export it for the ESP32.

Usage (in cmd):
    cd /d C:\lumo
    python train_model.py --features results\features_mpu1_win60.csv --out model_out

Outputs (in --out):
    model.json            mean, inverse covariance, Warning / Danger thresholds
    intellibridge_model.h C header with the same numbers, for the ESP32 firmware
    report.txt            honest evaluation (leave-one-group-out)
    scores.png            plot of file scores vs thresholds (needs matplotlib)
"""
import argparse, json, os
import numpy as np, pandas as pd
from sklearn.covariance import LedoitWolf
from sklearn.metrics import roc_auc_score

ap = argparse.ArgumentParser()
ap.add_argument('--features', required=True)
ap.add_argument('--out', default='model_out')
ap.add_argument('--warn_pct', type=float, default=95)
ap.add_argument('--danger_pct', type=float, default=99)
a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)

d = pd.read_csv(a.features)
FC = [c for c in d.columns if c.startswith('f') and c[1:].isdigit()]

def fit(X):
    lw = LedoitWolf().fit(X)             # shrinkage keeps the covariance stable with little data
    return lw.location_, np.linalg.inv(lw.covariance_)

def score(X, mu, P):
    z = X - mu
    return np.sqrt(np.einsum('ij,jk,ik->i', z, P, z))

# ---- 1. honest evaluation: leave one group out ------------------------------
# train on healthy windows of the other 5 groups, test on the held-out group
d['score'] = np.nan
for g in d.group.unique():
    tr = d[(d.group != g) & (d.label == 0)][FC].values
    mu, P = fit(tr)
    m = d.group == g
    d.loc[m, 'score'] = score(d.loc[m, FC].values, mu, P)

hw = d[d.label == 0].score.values                  # cross-validated healthy window scores
warn = float(np.percentile(hw, a.warn_pct))
danger = float(np.percentile(hw, a.danger_pct))

f = d.groupby(['file', 'group', 'label']).agg(score=('score', 'mean'), rms=('rms', 'mean'), T=('T', 'mean')).reset_index()
def risk(s): return 'Danger' if s >= danger else ('Warning' if s >= warn else 'Safe')
f['risk'] = f.score.map(risk)

lines = []
lines.append('INTELLIBRIDGE MODEL REPORT (leave-one-group-out, file = mean of its 60 s windows)')
lines.append(f'Warning threshold = p{a.warn_pct:g} of healthy scores = {warn:.2f}')
lines.append(f'Danger  threshold = p{a.danger_pct:g} of healthy scores = {danger:.2f}\n')
lines.append(f'{"group":10s} {"AUC model":>10s} {"AUC rms":>8s}  healthy S/W/D   damaged S/W/D')
for g, x in f.groupby('group'):
    h = x[x.label == 0].risk.value_counts(); dm = x[x.label == 1].risk.value_counts()
    cnt = lambda s: '/'.join(str(int(s.get(k, 0))) for k in ('Safe', 'Warning', 'Danger'))
    lines.append(f'{g:10s} {roc_auc_score(x.label, x.score):10.2f} {roc_auc_score(x.label, x.rms):8.2f}  {cnt(h):>13s}   {cnt(dm):>13s}')
tot_d = f[f.label == 1]; tot_h = f[f.label == 0]
lines.append(f'\nAll groups: damaged flagged Warning or Danger: {(tot_d.risk != "Safe").sum()} / {len(tot_d)}')
lines.append(f'            damaged flagged Danger:            {(tot_d.risk == "Danger").sum()} / {len(tot_d)}')
lines.append(f'            healthy flagged Warning or Danger: {(tot_h.risk != "Safe").sum()} / {len(tot_h)}')
lines.append(f'            healthy flagged Danger:            {(tot_h.risk == "Danger").sum()} / {len(tot_h)}')
lines.append(f'Mean file AUC: model {np.mean([roc_auc_score(x.label, x.score) for _, x in f.groupby("group")]):.2f}, '
             f'fixed RMS {np.mean([roc_auc_score(x.label, x.rms) for _, x in f.groupby("group")]):.2f}')
lines.append('\nLimits: 5 healthy + 5 damaged files per group, one tower, simulated sensor noise.')

# ---- 2. final model: train on ALL healthy windows --------------------------
mu, P = fit(d[d.label == 0][FC].values)
model = dict(features=FC, mean=mu.tolist(), inv_cov=P.tolist(), warn=warn, danger=danger)
json.dump(model, open(os.path.join(a.out, 'model.json'), 'w'))

# ---- 3. C header for the ESP32 ---------------------------------------------
n = len(FC)
h = ['// Auto-generated by train_model.py - do not edit', '#pragma once', f'#define IB_NFEAT {n}',
     f'static const float IB_WARN = {warn:.4f}f;', f'static const float IB_DANGER = {danger:.4f}f;',
     'static const float IB_MEAN[IB_NFEAT] = {' + ', '.join(f'{v:.6f}f' for v in mu) + '};',
     'static const float IB_INVCOV[IB_NFEAT][IB_NFEAT] = {']
for row in P: h.append('  {' + ', '.join(f'{v:.6f}f' for v in row) + '},')
h += ['};', '',
      '// Mahalanobis distance of one feature vector x[IB_NFEAT]',
      'static inline float ib_score(const float *x) {',
      '  float z[IB_NFEAT], s = 0;',
      '  for (int i = 0; i < IB_NFEAT; i++) z[i] = x[i] - IB_MEAN[i];',
      '  for (int i = 0; i < IB_NFEAT; i++) { float t = 0; for (int j = 0; j < IB_NFEAT; j++) t += IB_INVCOV[i][j] * z[j]; s += z[i] * t; }',
      '  return sqrtf(s);', '}',
      '// 0 = Safe, 1 = Warning, 2 = Danger',
      'static inline int ib_risk(float s) { return s >= IB_DANGER ? 2 : (s >= IB_WARN ? 1 : 0); }']
open(os.path.join(a.out, 'intellibridge_model.h'), 'w').write('\n'.join(h) + '\n')

# sanity check: C-style maths == numpy maths
x = d[FC].values[0]; z = x - np.array(model['mean']); chk = float(np.sqrt(z @ np.array(model['inv_cov']) @ z))
lines.append(f'\nSanity check (header maths vs numpy): {chk:.4f} vs {score(x[None], mu, P)[0]:.4f}')
lines.append(f'Model size: {n} means + {n*n} matrix values = {(n + n*n)*4/1024:.1f} KB as float32 (fits an ESP32 easily).')

open(os.path.join(a.out, 'report.txt'), 'w').write('\n'.join(lines))
print('\n'.join(lines))

# ---- 4. plot ---------------------------------------------------------------
try:
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(9, 4.5))
    groups = list(f.group.unique())
    for i, g in enumerate(groups):
        x = f[f.group == g]
        ax.scatter([i - .12] * (x.label == 0).sum(), x[x.label == 0].score, c='tab:green', s=40, label='healthy' if i == 0 else '')
        ax.scatter([i + .12] * (x.label == 1).sum(), x[x.label == 1].score, c='tab:red', s=40, label='damaged' if i == 0 else '')
    ax.axhline(warn, c='orange', ls='--', label='Warning'); ax.axhline(danger, c='red', ls='--', label='Danger')
    ax.set_xticks(range(len(groups))); ax.set_xticklabels(groups, rotation=20); ax.set_yscale('log')
    ax.set_ylabel('anomaly score (log)'); ax.set_title('IntelliBridge anomaly score per 10-min file (held-out groups)')
    ax.legend(); plt.tight_layout(); plt.savefig(os.path.join(a.out, 'scores.png'), dpi=150)
    print('saved scores.png')
except ImportError:
    print('matplotlib not installed: run  pip install matplotlib  to get scores.png')
