r"""Export the trained IntelliBridge danger model to a C header for the ESP32.
Run:  python export_esp32.py      -> writes intellibridge_danger.h and intellibridge_demo.ino
The header holds 7 small lookup tables (one per sensor) and one 51x51 table that combines them.
Total about 3 KB. No floating-point library needed except basic maths.
"""
import numpy as np, joblib, intellibridge_predict as ib, intellibridge_safety as sf
b = sf.load()
NPT, G1, G2, MAXV, MAXR = 32, 51, 51, 100.0, 600.0
h = ['// Auto-generated by export_esp32.py - do not edit', '#pragma once', '#include <math.h>', f'#define IB_NS 7', f'#define IB_NPT {NPT}', f'#define IB_G1 {G1}', f'#define IB_G2 {G2}']
X, Y = [], []
for k in ib.PF:
    top = ib.CURVES[k][0][-1]
    bp = np.array(ib.CURVES[k][0], float)
    others = np.setdiff1d(np.round(np.linspace(0, top, 400), 6), bp)
    pick = others[np.linspace(1, len(others) - 2, NPT - len(bp)).round().astype(int)]
    xs = np.sort(np.concatenate([bp, pick]))
    assert len(xs) == NPT and np.all(np.diff(xs) > 0)
    X.append(xs); Y.append(b['iso'][k].predict(xs))
h.append('// sensor order: ' + ', '.join(ib.PF))
h.append('static const float IB_X[IB_NS][IB_NPT] = {' + ','.join('{' + ','.join(f'{v:.4f}f' for v in r) + '}' for r in X) + '};')
h.append('static const float IB_Y[IB_NS][IB_NPT] = {' + ','.join('{' + ','.join(f'{v:.2f}f' for v in r) + '}' for r in Y) + '};')
mx = np.linspace(0, MAXV, G1); rs = np.linspace(0, MAXR, G2)
M, R = np.meshgrid(mx, rs, indexing='ij')
T = np.clip(b['model'].predict(np.column_stack([M.ravel(), R.ravel()])), 1, 100).reshape(G1, G2)
h.append('static const uint8_t IB_T[IB_G1][IB_G2] = {' + ','.join('{' + ','.join(str(int(round(v))) for v in r) + '}' for r in T) + '};')
h.append(f'#define IB_MAXV {MAXV}f\n#define IB_MAXR {MAXR}f')
h.append(r'''
static float ib_interp(const float *x, const float *y, float v) {
  if (v <= x[0]) return y[0];
  if (v >= x[IB_NPT - 1]) return y[IB_NPT - 1];
  int i = 1; while (v > x[i]) i++;
  float t = (v - x[i - 1]) / (x[i] - x[i - 1]); return y[i - 1] + t * (y[i] - y[i - 1]);
}
// readings -> danger level 1..100 ; cls: 0 Safe, 1 Warning, 2 Danger
static int ib_danger(float vib, float freq, float tilt, float crack, float water, float strain, float temp, int *cls) {
  float fc = freq + 0.015f * (temp - 20.0f);
  float th = 6.0f * (temp - 20.0f), ct = 0.02f * (temp - 20.0f);
  float p[IB_NS] = { fabsf(vib), fmaxf(0.0f, fminf(4.0f - freq, 4.0f - fc)), fmaxf(0.0f, fminf(freq - 4.5f, fc - 4.5f)), fabsf(tilt),
                     fminf(fabsf(crack), fabsf(crack - ct)), fmaxf(0.0f, water), fminf(fabsf(strain), fabsf(strain - th)) };
  float mx = 0, sum = 0;
  for (int k = 0; k < IB_NS; k++) { float s = ib_interp(IB_X[k], IB_Y[k], p[k]); sum += s; if (s > mx) mx = s; }
  float u = fminf(mx, IB_MAXV) / IB_MAXV * (IB_G1 - 1), w = fminf(sum - mx, IB_MAXR) / IB_MAXR * (IB_G2 - 1);
  int i = (int)u, j = (int)w; if (i > IB_G1 - 2) i = IB_G1 - 2; if (j > IB_G2 - 2) j = IB_G2 - 2;
  float a = u - i, c = w - j;
  float L = (1 - a) * ((1 - c) * IB_T[i][j] + c * IB_T[i][j + 1]) + a * ((1 - c) * IB_T[i + 1][j] + c * IB_T[i + 1][j + 1]);
  int lv = (int)(L + 0.5f); if (lv < 1) lv = 1; if (lv > 100) lv = 100;
  *cls = lv >= 65 ? 2 : (lv >= 30 ? 1 : 0); return lv;
}''')
open('intellibridge_danger.h', 'w').write('#include <stdint.h>\n' + '\n'.join(h) + '\n')
print('header bytes of tables ~', (2 * 7 * NPT * 4 + G1 * G2) , 'B')
